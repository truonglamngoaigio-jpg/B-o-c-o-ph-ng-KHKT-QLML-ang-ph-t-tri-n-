function buildProjectsAndReports(): {
  projects: WaterProject[];
  reports: WeeklyReport[];
} {
  const projects: WaterProject[] = [];
  const reports: WeeklyReport[] = [];

  for (const item of RAW_PROJECTS) {
    const { capitalGroup, areaGroup } = inferProjectGrouping(
      item.id,
      item.location
    );
    const hasWaterPipes = projectHasWaterPipes({
      category: item.category,
      name: item.name,
      totalPlannedVolume: item.cumulativeText,
    });
    const approvedPipes = hasWaterPipes
      ? parseApprovedPipesFromText(item.id, item.cumulativeText, item.name)
      : undefined;

    const isSettled = isProjectSettled({ targetEndDate: item.progressLabel });

    projects.push({
      id: item.id,
      code: item.code,
      name: item.name,
      capitalGroup,
      areaGroup,
      location: item.location,
      category: item.category,
      supervisorId: item.supervisorId,
      budgetBillionVND: 0,
      targetEndDate: item.progressLabel,
      totalPlannedVolume: item.cumulativeText,
      ...(approvedPipes !== undefined ? { approvedPipes } : {}),
      ...(isSettled
        ? {
            reportLocked: true,
            reportLockedAt: WEEK_SUBMIT_STAMP[DEFAULT_WEEK_ID],
          }
        : {}),
    });

    const seededStage =
      item.progressLabel &&
      item.progressLabel.trim().toUpperCase() !== 'CHƯA CẬP NHẬT'
        ? normalizeProjectStage(item.progressLabel)
        : undefined;

    const explicitWeeks = item.weeklyLogs ?? {};
    for (const [weekId, log] of Object.entries(explicitWeeks)) {
      reports.push({
        id: `${item.id}__${weekId}`,
        projectId: item.id,
        weekId,
        supervisorIdAtSubmission: item.supervisorId,
        submittedAt: WEEK_SUBMIT_STAMP[weekId] ?? '14/11/2026 17:00',
        status: log.status ?? 'on_track',
        ...(seededStage ? { projectStage: seededStage } : {}),
        cumulativeProgress: log.pct ?? item.defaultPct,
        weeklyProgressDelta: log.delta ?? 0,
        weeklyVolume: log.vol,
        summary: log.summary,
        issues: log.issues ?? '',
        leaderNote: log.note ?? '',
      });
    }

    // Ensure DEFAULT_WEEK_ID (Tuần 2 / T11) reflects the master sheet status even when no week-specific cell changed in that column
    if (!explicitWeeks[DEFAULT_WEEK_ID]) {
      const label = item.progressLabel;
      if (label === 'ĐÃ QUYẾT TOÁN' || label === 'ĐANG QT' || label === 'ĐANG QUYẾT TOÁN') {
        reports.push({
          id: `${item.id}__${DEFAULT_WEEK_ID}`,
          projectId: item.id,
          weekId: DEFAULT_WEEK_ID,
          supervisorIdAtSubmission: item.supervisorId,
          submittedAt: WEEK_SUBMIT_STAMP[DEFAULT_WEEK_ID],
          status: 'on_track',
          ...(seededStage ? { projectStage: seededStage } : {}),
          cumulativeProgress: item.defaultPct,
          weeklyProgressDelta: 0,
          weeklyVolume: item.cumulativeText,
          summary: `Trạng thái tổng hợp: ${label}.`,
          issues: '',
          leaderNote: '',
        });
      } else if (label === 'TẠM NGỪNG') {
        reports.push({
          id: `${item.id}__${DEFAULT_WEEK_ID}`,
          projectId: item.id,
          weekId: DEFAULT_WEEK_ID,
          supervisorIdAtSubmission: item.supervisorId,
          submittedAt: WEEK_SUBMIT_STAMP[DEFAULT_WEEK_ID],
          status: 'delayed',
          ...(seededStage ? { projectStage: seededStage } : {}),
          cumulativeProgress: item.defaultPct,
          weeklyProgressDelta: 0,
          weeklyVolume: item.cumulativeText,
          summary: `Trạng thái tổng hợp: ${label}.`,
          issues: 'Công trình đang tạm ngưng thi công.',
          leaderNote: '',
        });
      } else if (label === 'THIẾT KẾ' || label === 'CÔNG TRÌNH MỚI CẬP NHẬT') {
        reports.push({
          id: `${item.id}__${DEFAULT_WEEK_ID}`,
          projectId: item.id,
          weekId: DEFAULT_WEEK_ID,
          supervisorIdAtSubmission: item.supervisorId,
          submittedAt: WEEK_SUBMIT_STAMP[DEFAULT_WEEK_ID],
          status: 'attention',
          ...(seededStage ? { projectStage: seededStage } : {}),
          cumulativeProgress: item.defaultPct,
          weeklyProgressDelta: 0,
          weeklyVolume: item.cumulativeText,
          summary: `Giai đoạn hiện tại: ${label}.`,
          issues: '',
          leaderNote: '',
        });
      }
      // Note: 'CHƯA THI CÔNG', 'CÔNG TRÌNH KỲ VỌNG', 'CHƯA CẬP NHẬT' remain pending/unreported for Tuần 2/T11 unless explicit weeklyLogs existed
    }
  }

  return { projects, reports };
}

